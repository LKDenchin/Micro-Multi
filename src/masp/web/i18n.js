export function translateUiText(value) { return locale === 'en-US' ? textValue(String(value)) : String(value); }

function translate(root) {
  if (!root) return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  const texts = [];
  if (root.nodeType === Node.TEXT_NODE) texts.push(root);
  while (walker.nextNode()) texts.push(walker.currentNode);
  for (const node of texts) {
    if (node.parentElement?.closest(excluded)) continue;
    const prior = originals.get(node);
    const source = prior && node.nodeValue === textValue(prior) ? prior : node.nodeValue;
    if (textValue(source) === source) continue;
    originals.set(node, source);
    const next = locale === 'en-US' ? textValue(source) : source;
    if (node.nodeValue !== next) node.nodeValue = next;
  }
  const elements = root.nodeType === Node.ELEMENT_NODE ? [root, ...root.querySelectorAll('*')] : [];
  for (const el of elements) for (const attr of ['title', 'aria-label', 'placeholder']) {
    if (el.matches('.conversation, .project-link, #project-name')) continue;
    const value = el.getAttribute(attr);
    if (!value) continue;
    const saved = attributeOriginals.get(el) || {};
    const source = saved[attr] && value === textValue(saved[attr]) ? saved[attr] : value;
    if (textValue(source) === source) continue;
    saved[attr] = source; attributeOriginals.set(el, saved);
    const next = locale === 'en-US' ? textValue(source) : source;
    if (value !== next) el.setAttribute(attr, next);
  }
}
